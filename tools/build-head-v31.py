"""Author a reusable facial surface with two clean almond eye openings.

The runtime supplies the head proportions and facial planes. Topology is shared
by every base and face variant; the existing skeleton and saves are retained.
"""
import json
from pathlib import Path
import numpy as np
from scipy.spatial import Delaunay

ROOT=Path(__file__).resolve().parents[1]
ROWS,COLS=88,64
EYEV=.60
def aperture(u,side):
    t=(u-side*.415)/.245
    if abs(t)>=1: return None
    arc=max(0,1-t*t)**.68
    mid=EYEV+side*t*.006
    return mid-.023*arc,mid+.034*arc
def inside(u,v):
    for s in [-1,1]:
        a=aperture(u,s)
        if a and a[0]+1e-7<v<a[1]-1e-7:return True
    return False
points=[]
for r in range(ROWS+1):
    v=r/ROWS
    for c in range(COLS+1):
        u=c/COLS*2-1
        if not inside(u,v):points.append([u,v])
for s in [-1,1]:
    for upper in [False,True]:
        for i in range(61):
            t=i/60*2-1;u=s*.415+t*.245
            arc=max(0,1-t*t)**.68
            points.append([u,EYEV+s*t*.006+(.034 if upper else -.023)*arc])
points=np.unique(np.round(points,9),axis=0)
tri=Delaunay(points)
faces=[]
for f in tri.simplices:
    centre=points[f].mean(axis=0)
    if not inside(*centre):faces.append(f.tolist())
params=[[float(u),float(v),1] for u,v in points]
lookup={(int(round(u)),int(round(v*ROWS))):i for i,(u,v) in enumerate(points) if abs(abs(u)-1)<1e-8}
back=[]
for r in range(ROWS+1):
    ring=[]
    for c in range(33):
        u=-np.cos(c/32*np.pi)
        if c in (0,32):idx=lookup[(int(round(u)),r)]
        else:idx=len(params);params.append([float(u),r/ROWS,-1])
        ring.append(idx)
    back.append(ring)
for r in range(ROWS):
    for c in range(32):
        a,b=back[r][c],back[r+1][c]
        faces.extend([[a,b,back[r][c+1]],[back[r][c+1],b,back[r+1][c+1]]])
# A small flat crown cap avoids a pinched pole; the neck remains open inside the body.
upper=[i for i,p in enumerate(params) if p[1]==1]
centre=len(params);params.append([0,1.0001,0])
# Boundary order follows the front (+Z) then the back (-Z).
front=sorted([i for i in upper if params[i][2]==1],key=lambda i:params[i][0])
rear=sorted([i for i in upper if params[i][2]==-1],key=lambda i:-params[i][0])
loop=front+rear
for a,b in zip(loop,loop[1:]+loop[:1]):faces.append([a,b,centre])
data={'params':params,'indices':np.array(faces).reshape(-1).tolist(),'eyeV':EYEV,'range':[1.49,1.805]}
out=ROOT/'dist/src/head-v31-data.js'
out.write_text('/* Authored facial topology; generated by tools/build-head-v31.py. */\nconst HEAD31_DATA='+json.dumps(data,separators=(',',':'))+';\n')
print(json.dumps({'vertices':len(params),'triangles':len(faces),'file':str(out)}))
