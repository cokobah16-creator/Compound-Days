// tools/reader-v38.cjs: prints section 3 of docs/READER_gist.md ("Every line, as the game ships it") from the game's own copy tables:
// GIST38.LINES and GIST38.UI (dist/src/gist-v38.js), FOUND38.SPEECH, FOUND38.UI, FOUND38.LOST and FOUND38.SHELLS (dist/src/found-v38.js).
// The two modules are run in an empty sandbox (no game, no browser): only their tables are read. Every string in those tables is printed once.
// Usage: node tools/reader-v38.cjs > section3.md   (then paste it over section 3 of the sheet)
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const SRC = path.join(__dirname, '..', 'dist', 'src');
const ctx = vm.createContext({ HOTSPOT_HOOKS: [], ACT_HOOKS: [], console: { warn() {}, log() {} } });
for (const f of ['found-v38.js', 'gist-v38.js']) vm.runInContext(fs.readFileSync(path.join(SRC, f), 'utf8'), ctx, { filename: f });
const T = JSON.parse(vm.runInContext('JSON.stringify({L:GIST38.LINES,U:GIST38.UI,S:FOUND38.SPEECH,FU:FOUND38.UI,LOST:FOUND38.LOST,SHELLS:FOUND38.SHELLS,WHERE:FOUND38.WHERE,ASK:FOUND38.CARVE_ASK})', ctx));
const { L, U, S, FU, LOST, SHELLS, WHERE } = T;
const NAME = { tunde: 'Tunde', nkechi: 'Mama Nkechi', ada: 'Ada', bassey: 'Mr. Bassey', oyelaran: 'Mrs. Oyelaran' };
const WHO = Object.keys(NAME);
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const out = [];
const p = s => out.push(s);
const table = (head, rows) => { p('| ' + head.join(' | ') + ' |'); p('|' + head.map(() => '---').join('|') + '|'); for (const r of rows) p('| ' + r.map(cell).join(' | ') + ' |'); p(''); };
const leaves = (o, pre, acc) => { if (typeof o === 'string') acc.push([pre, o]); else if (Array.isArray(o)) o.forEach((v, k) => leaves(v, pre + '[' + k + ']', acc)); else if (o && typeof o === 'object') for (const k in o) leaves(o[k], pre ? pre + '.' + k : k, acc); return acc; };
const thing = id => L.thing[id];
p('## 3. Every line, as the game ships it');
p('');
p('Generated by `node tools/reader-v38.cjs` from the copy tables in `dist/src/gist-v38.js` and `dist/src/found-v38.js`. Every string in those tables is below, once.');
p('');
p('### Greetings (lines 1 and 2; one of four, not repeated until all four are used)');
p('');
table(['Id', 'Who', 'Line'], WHO.flatMap(k => L.o[k].map(e => [e[0], NAME[k], e[1] + (e[2] === 'bench' ? ' *(only with Ada’s bench placed)*' : '')])));
p('### One-time openers (each replaces that neighbour’s greeting once, ever)');
p('');
const ONCE = { nkFirst: 'her first gist (normally the household’s first)', tuSoon: 'his first gist', adShelf: 'her first gist after the shelf goes up' };
table(['Id', 'Who', 'When', 'Line'], Object.entries(L.once).map(([k, e]) => [e[1], NAME[e[0]], ONCE[k] || k, e[2]]));
p('### Fallback lines (shown only if a line cannot be found; the v35 evening’s own fallbacks cover the other three)');
p('');
table(['Who', 'Line'], Object.entries(L.fallback).map(([k, t]) => [NAME[k], t]));
p('### Tips about tomorrow: lost things (told by the owner, or to the owner’s face)');
p('');
table(['Id', 'Teller', 'Line', 'Owner’s answer-back'], Object.entries(L.lost).map(([id, e]) => { const it = LOST.find(x => x.id === id), b = L.back[id];
  return [e[1], NAME[e[0]], e[2], it && it.owner === e[0] ? '(the owner tells it)' : b ? b[1] + ' (' + b[0] + ')' : '']; }));
p('### Reminders (a thing out now, told at most once before), with the owner’s answer-back');
p('');
p(`The reminder is one line, \`${L.remind[0]}\`: “${L.remind[1]}”. {Area} is the place as a neighbour says it (\`FOUND38.LOST[].say\`); Today and the night page keep the map words (\`area\`, below). As said, for each thing:`);
p('');
table(['Thing', 'Line as said'], LOST.filter(it => it.id !== 'glasses').map(it => [it.id, L.remind[1].replace('{owner}', NAME[it.owner]).replace('{thing}', thing(it.id)).replace('{Area}', it.say)]));
table(['Id', 'Line'], [[L.remindGlasses[0], L.remindGlasses[1] + ' *(the glasses’ first reminder)*']]);
table(['Id', 'Owner answering back', 'Line'], Object.entries(L.backR).map(([k, e]) => [e[0], NAME[k], e[1]]));
p('### The thing in your pocket (said by a guest who is not its owner)');
p('');
p(`One line, \`${L.pocket[0]}\`: “${L.pocket[1]}”, with {thing} and {Where} from these words:`);
p('');
table(['Thing', '{thing}', 'Its owner', '{Where}'], LOST.map(it => [it.id, L.pocketThing[it.id], NAME[it.owner], L.where[it.owner]]));
p('Things by name in speech (“Nobody has found Ada’s chisel yet”), and on Today and the night page: ' + LOST.map(it => it.id + ' “' + L.thing[it.id] + '”').join(', ') + '.');
p('');
p('### The wash (shells at the water’s edge tomorrow afternoon)');
p('');
table(['Id', 'Who', 'Line'], Object.entries(L.wash).map(([k, e]) => [e[0], k === 'adaCowrie' ? 'Ada (until the household has a cowrie)' : NAME[k], e[1]]));
p('### About today (line 3): a return retold by a guest who is not the owner, or what the household did');
p('');
table(['Id', 'When', 'Line'], Object.entries(L.told).map(([k, e]) => [e[0], 'the ' + thing(k) + ' given back today', e[1]]).concat(Object.entries(L.today).map(([k, e]) => [e[0], { catch: 'three catches today', shells: 'three shells today', harvest: 'a harvest today' }[k] || k, e[1]])));
p('### Reactions (line 5 when nobody answers back)');
p('');
table(['Id', 'Who', 'Line'], WHO.flatMap(k => L.react[k].map(e => [e[0], NAME[k], e[1]])));
p('### Plain gist (when there is nothing to tell). The second line of each is new in this build, not in the spec (question 13).');
p('');
table(['Id', 'Who', 'Line'], WHO.flatMap(k => L.plain[k].map(e => [e[0], NAME[k], e[1]])));
p('### Goodbyes (the last line)');
p('');
table(['Id', 'Who', 'Line'], WHO.flatMap(k => L.bye[k].map(e => [e[0], NAME[k], e[1]])));
p('### Thank-yous in the return panel (`FOUND38.SPEECH.ty`; a second block tells you about the next thing)');
p('');
table(['Id', 'Who', 'Line'], Object.entries(S.ty).flatMap(([k, list]) => list.map((t, n) => ['gs38-ty-' + (k === 'glassesLate' ? 'glasses-late' : k) + (list.length > 1 ? '-' + (n + 1) : ''), NAME[LOST.find(x => x.id === (k === 'glassesLate' ? 'glasses' : k)).owner] + (k === 'glassesLate' ? ' (given back after half past three)' : k === 'glasses' ? ' (given back before half past three)' : ''), t])));
p('### Ada names a fish to carve (`FOUND38.SPEECH.ask`): in her talk, for today, or in the gist before the goodbye, for tomorrow; once a day at most');
p('');
p('Three lines each for the five day fish, one a day by the day’s number; one each for the catfish. {thing}: ' + Object.entries(S.fishSay).map(([k, v]) => k + ' “' + v + '”').join(', ') + '; her order: ' + T.ASK.join(', ') + '.');
p('');
const askRows = []; for (const [k, v] of Object.entries(S.ask)) for (const e of Array.isArray(v[0]) ? v : [v]) askRows.push([e[0], { gist: 'the gist, for tomorrow', talk: 'her talk, for today', catGist: 'the gist, the catfish', catTalk: 'her talk, the catfish' }[k] || k, e[1]]);
table(['Id', 'Where', 'Line'], askRows);
p('### Ada’s carvings: her line when you give her the fish (`FOUND38.SPEECH.carve`)');
p('');
table(['Id', 'Fish', 'Line'], Object.entries(S.carve).map(([k, t]) => ['gs38-ada-' + k, S.fishSay[k] || k, t]));
p('### The lost things (`FOUND38.LOST`): the prompt, the toast, the give label and the words for each');
p('');
table(['Thing', 'Prompt', 'Pick-up toast', 'Toast once its owner is known', 'Give label'], LOST.map(it => [it.id, 'Pick up ' + it.pickLabel, it.pickToast, it.pickToastKnown || '(the same)', it.giveLabel]));
table(['Thing', 'Long name (Today’s pocket row)', 'Area (Today, the night page)', 'Spoken place (reminders)'], LOST.map(it => [it.id, it.long, it.area, it.say]));
p('Where each owner is (Today’s pocket row once the owner is known): ' + Object.entries(WHERE).map(([k, v]) => NAME[k] + ': “' + v + '”').join(' ') );
p('');
p('### Shell kinds (`FOUND38.SHELLS`)');
p('');
table(['Kind', 'Name', 'On the shelf panel', 'Toast'], SHELLS.map(s => [s.id, s.name, s.short, s.toast + ' (plus “' + FU.newKind.trim() + '” for a new kind)']));
p('### The interface (plain English): every string in `GIST38.UI` and `FOUND38.UI`, by its key');
p('');
p('{a}, {b}, {who}, {owner}: a neighbour’s name; {thing}, {long}, {area}, {where}, {hint}: the words above; {fish}: the fish’s name; {n}, {m}, {have}, {of}, {k}, {g}, {r}, {q}, {price}, {until}: counts, money and times filled in by the game.');
p('');
table(['Key', 'Text'], leaves(U, 'GIST38.UI', []).concat(leaves(FU, 'FOUND38.UI', [])));
process.stdout.write(out.join('\n'));
